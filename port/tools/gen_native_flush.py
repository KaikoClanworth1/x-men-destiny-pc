"""Generate src/native/native_flush_hooks.cpp: on every function of the game's
Direct3D library that src/native/native_hooks.cpp doesn't hook itself, a hook
that lets the native renderer make a pending BeginVertices draw first (see
native_hooks.cpp for why).

    python gen_native_flush.py [lo hex] [hi hex]

The function list is the cache tools/d3d_match.py left in runs/.
"""
import glob
import os
import pickle
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))


def main():
    lo = int(sys.argv[1], 16) if len(sys.argv) > 1 else 0x82725000
    hi = int(sys.argv[2], 16) if len(sys.argv) > 2 else 0x82750000
    funcs = None
    for path in glob.glob(os.path.join(ROOT, "runs", "d3d_match_*.pkl")):
        with open(path, "rb") as f:
            data = pickle.load(f)
        if len(data) > 70000:
            funcs = data
    hooked = set()
    with open(os.path.join(ROOT, "src", "native", "native_hooks.cpp")) as f:
        hooked = {int(m, 16) for m in re.findall(r"REX_HOOK_RAW\(sub_([0-9A-F]{8})\)", f.read())}
    addresses = sorted(a for a in funcs if lo <= a < hi and a not in hooked)
    lines = [
        "// Generated by tools/gen_native_flush.py - do not edit.",
        "// A pending BeginVertices draw is made before any other D3D library call.",
        "",
        "#include <rex/hook.h>",
        "#include <rex/ppc.h>",
        "",
        '#include "generated/default/xmd_init.h"',
        '#include "native/native_renderer.h"',
        "",
        "#define XMD_FLUSH_HOOK(name)                 \\",
        "  REX_EXTERN(__imp__##name);                 \\",
        "  REX_HOOK_RAW(name) {                       \\",
        "    xmd::native::BeforeD3DCall();            \\",
        "    __imp__##name(ctx, base);                \\",
        "  }",
        "",
    ]
    lines += [f"XMD_FLUSH_HOOK(sub_{a:08X})" for a in addresses]
    out = os.path.join(ROOT, "src", "native", "native_flush_hooks.cpp")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{len(addresses)} hooks -> {out}")


if __name__ == "__main__":
    main()
