r"""Writes src\mod_menu_tables.inc for the mod menu (src\mod_menu.cpp): the game's in-engine cut-scenes, found in
the scripts of the level archives (tools\lua_scripts.py -> runs\lua\*.lua). A scene is a "cineplex" actor that a
script starts with cineplexaction("<actor id>", 0); it only plays when its own archive (the load("NN_...") before
the call) and the character packs it uses (load("cyclops8") ...) are loaded - those go into the table with it.
    python tools\lua_scripts.py
    python tools\mod_menu_tables.py
"""
import glob, os, re, sys
port = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PACKS = {"magneto1", "mystique3", "nightcrawler4", "luis5", "gambit6", "surge7", "cyclops8", "wolverine9",
         "juggernaut10", "caliban12", "toad13", "quicksilver14", "pixie15", "colossus16", "pyro17", "iceman18",
         "forge19", "northstar20", "emma22"}
call = re.compile(r'\b(load|unload|cineplexaction)\(\s*["\']([^"\']+)["\']\s*(?:,\s*(\d))?')
rows, seen = [], set()
for f in sorted(glob.glob(os.path.join(port, "runs", "lua", "*.lua"))):
    script = os.path.basename(f)[:-4]
    text = open(f, "rb").read().decode("latin1")
    packs, cinema, number = [], "", 0
    for m in call.finditer(text):
        what, name, arg = m.groups()
        low = name.lower()
        if what == "load":
            if low in PACKS and low not in packs: packs.append(low)
            elif re.match(r"\d", name): cinema = name
        elif what == "unload":
            if low in packs: packs.remove(low)
        elif arg == "0" and name not in seen:
            seen.add(name)
            number += 1
            # (a cinematic's own archive holds its script: nothing else to load but itself)
            own = script if re.match(r"\d", script) else cinema
            rows.append((script, number, name, own, list(packs)))
# Only the scenes seen to play (tools\mod_sweep.ps1 -Kind scene, 2026-11-20: tools\mod_menu_scenes.txt, lines
# "<entry id>|<checkpoint entry id it played from>"), each with that checkpoint: the menu loads it first.
def slug(text):
    out = ""
    for c in text:
        if c.isalnum(): out += c.lower()
        elif out and out[-1] != "_": out += "_"
    return out.rstrip("_")
checkpoints = {}   # entry id -> (name, mission)
source = open(os.path.join(port, "src", "mod_menu.cpp"), encoding="utf-8").read()
block = source[source.index("const std::vector<Mission>& Missions()"):source.index("const char* const kArenas[]")]
for m in re.finditer(r'\{"[^"]*", (\d+),\s*\{([^}]*)\}\}', block):
    for name in re.findall(r'"([^"]+)"', m.group(2)):
        checkpoints["cp_" + slug(name)] = (name, int(m.group(1)))
plays = {}
seen_file = os.path.join(port, "tools", "mod_menu_scenes.txt")
if os.path.exists(seen_file):
    for line in open(seen_file):
        parts = line.strip().split("|")
        if len(parts) == 2 and parts[1] in checkpoints: plays[parts[0]] = checkpoints[parts[1]]
kept = 0
with open(os.path.join(port, "src", "mod_menu_tables.inc"), "w", newline="\n") as o:
    o.write("// Generated by tools/mod_menu_tables.py - the game's in-engine cut-scenes that were seen to play:\n"
            "// {script archive, scene number, actor id, the scene's own archive, character packs it needs,\n"
            "//  the checkpoint it plays from, that checkpoint's mission number}.\n")
    for script, number, actor, own, packs in rows:
        entry = "scene_%s_%d" % (slug(script), number)
        if entry not in plays:
            # (--all: every scene of the scripts, for the sweep that finds out which play)
            if "--all" not in sys.argv: continue
            plays[entry] = ("", -1)
        kept += 1
        o.write('{"%s", %d, "%s", "%s", "%s", "%s", %d},\n' % (script, number, actor, own, " ".join(packs), *plays[entry]))
print(len(rows), "scenes in the scripts,", kept, "kept")
