"""Generate src/d3d_trace_hooks.cpp: a recording hook on every function of the
game's Direct3D library (the XMD_D3D_TRACE build, see src/d3d_trace.cpp).

    python gen_d3d_trace.py [lo hex] [hi hex]

The function list is the cache tools/d3d_match.py left in runs/.
"""
import glob
import os
import pickle
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
PRESENT = 0x82738208  # hooked in d3d_trace.cpp itself (the frame counter)


def main():
    lo = int(sys.argv[1], 16) if len(sys.argv) > 1 else 0x82720000
    hi = int(sys.argv[2], 16) if len(sys.argv) > 2 else 0x82750000
    funcs = None
    for path in glob.glob(os.path.join(ROOT, "runs", "d3d_match_*.pkl")):
        with open(path, "rb") as f:
            data = pickle.load(f)
        if len(data) > 70000:
            funcs = data
    addresses = sorted(a for a in funcs if lo <= a < hi and a != PRESENT)
    lines = [
        "// Generated by tools/gen_d3d_trace.py - do not edit.",
        "// Recording hooks on the game's D3D library (XMD_D3D_TRACE builds).",
        "",
        "#include <cstdint>",
        "",
        "#include <rex/hook.h>",
        "#include <rex/ppc.h>",
        "",
        '#include "generated/default/xmd_init.h"',
        "",
        "namespace xmd::d3d_trace {",
        "void Enter(uint32_t index, const PPCContext& ctx);",
        "void Leave(uint32_t index, const PPCContext& ctx);",
        f"extern const uint32_t kFunctionCount = {len(addresses)};",
        "extern const uint32_t kFunctions[] = {",
    ]
    lines += [f"    0x{a:08X}," for a in addresses]
    lines += ["};", "}  // namespace xmd::d3d_trace", ""]
    for i, a in enumerate(addresses):
        lines += [
            f"REX_EXTERN(__imp__sub_{a:08X});",
            f"REX_HOOK_RAW(sub_{a:08X}) {{",
            f"  xmd::d3d_trace::Enter({i}, ctx);",
            f"  __imp__sub_{a:08X}(ctx, base);",
            f"  xmd::d3d_trace::Leave({i}, ctx);",
            "}",
        ]
    out = os.path.join(ROOT, "src", "d3d_trace_hooks.cpp")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{len(addresses)} hooks -> {out}")


if __name__ == "__main__":
    main()
